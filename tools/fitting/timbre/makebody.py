"""Fit the body filter for an instrument to its reference recordings and write
lib/body_<instrument>.lib.
   python makebody.py violin            first fit, straight from the recordings
   python makebody.py violin --correct  also apply the accumulated correction,
                                        refs/<instrument>-correction.npz
   python makebody.py violin --apply-diff   add the difference evaluate.py --correction last
                                        measured (refs/<instrument>-lastdiff.npz) to the
                                        accumulated correction, then fit with it"""
import os, sys, numpy as np
import body, bodyfit as BF

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
CFG = {
    "violin": dict(who="hahn", lo=180, poles=(36, 36, 18)),
    "cello":  dict(who="ma", lo=60, poles=(54, 24, 12)),
}

def target(inst):
    c = CFG[inst]
    d = np.load(os.path.join(ROOT, "refs", c["who"] + ".npz"))
    grid = 40 * 2 ** (np.arange(0, int(np.log2(14000 / 40) * 96) + 1) / 96)
    g, B, *_ = body.fit_body(d["f0"], d["H"], grid=grid, smooth_bins=1.0)
    return g, B

def smooth_oct(f, db, width):
    lg = np.log2(f)
    w = np.exp(-0.5 * ((lg[:, None] - lg[None, :]) / width) ** 2)
    return (w @ db) / w.sum(1)


def main(inst, correct=False, detail=1.0, poles=None, out_name=None):
    c = CFG[inst]
    g, B = target(inst)
    if detail != 1.0:
        # the measured fine structure is real but averaged down: scale it up
        Bs = smooth_oct(g, B, 1 / 6)
        B = Bs + detail * (B - Bs)
    if correct:
        cor = np.load(os.path.join(ROOT, "refs", f"{inst}-correction.npz"))
        B = B + np.interp(np.log2(g), np.log2(cor["f"]), cor["db"])
    n_lo, n_mid, n_hi = poles or c["poles"]
    pf = np.concatenate([np.geomspace(c["lo"] * 0.9, 1500, n_lo, endpoint=False),
                         np.geomspace(1500, 6000, n_mid, endpoint=False), np.geomspace(6000, 20000, n_hi)])
    secs, firt, fr, err, full = BF.design(g, B, pf, f_lo=c["lo"])
    # normalise: 0 dB average gain over 300 Hz - 5 kHz
    m = (fr > 300) & (fr < 5000)
    h = np.abs(BF.response(secs, firt, fr[m]))
    k = 1 / np.sqrt(np.mean(h ** 2))
    secs = [(b0 * k, b1 * k, a1, a2) for b0, b1, a1, a2 in secs]; firt = firt * k
    for a, b in ((c["lo"], 600), (600, 1500), (1500, 4000), (4000, 12000)):
        mm = (fr > a) & (fr < b)
        print(f"  fit error {a:5.0f}-{b:5.0f} Hz: {np.sqrt(np.mean(err[mm] ** 2)):.2f} dB")
    src = f"// Body of the {inst}: bridge force -> sound, fitted to the harmonic levels of the reference\n" \
          f"// recordings{' (with a correction from evaluate.py)' if correct else ''}. Generated by tools/fitting/timbre/makebody.py; do not edit.\n" \
          'import("stdfaust.lib");\n' + BF.faust("body", secs, firt)
    out = os.path.join(ROOT, "lib", out_name or f"body_{inst}.lib")
    open(out, "w").write(src)
    np.savez(os.path.join(ROOT, "refs", f"{inst}-bodytarget.npz"), f=g, db=B)
    print("wrote", out, len(secs), "resonators")

def apply_diff(inst, step=0.8):
    cp = os.path.join(ROOT, "refs", f"{inst}-correction.npz")
    lp = os.path.join(ROOT, "refs", f"{inst}-lastdiff.npz")
    last = np.load(lp)
    f = last["f"]; d = last["db"] * step
    if os.path.exists(cp):
        old = np.load(cp)
        d = d + np.interp(np.log2(f), np.log2(old["f"]), old["db"])
    d = np.clip(d, -12, 12)             # beyond this the filter cannot follow; do not let it run away
    np.savez(cp, f=f, db=d)
    os.remove(lp)                        # so the same difference is never added twice
    print("accumulated correction, dB:", " ".join(f"{int(a)}:{np.interp(a, f, d):+.1f}" for a in (200, 400, 800, 1600, 3200, 6400, 10000)))

if __name__ == "__main__":
    if "--apply-diff" in sys.argv:
        apply_diff(sys.argv[1])
    a = sys.argv
    det = float(a[a.index("--detail") + 1]) if "--detail" in a else 1.0
    pl = tuple(int(v) for v in a[a.index("--poles") + 1].split(",")) if "--poles" in a else None
    nm = a[a.index("--out") + 1] if "--out" in a else None
    main(a[1], "--correct" in a or "--apply-diff" in a, det, pl, nm)
