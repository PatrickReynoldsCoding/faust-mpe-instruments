"""Fit the trumpet's or the duduk's tone to measured harmonic levels (ROLI Seaboard demos).

The instrument's tone is a band-limited sawtooth through a bank of peaking filters (fixed centres,
RBJ peaking EQ) whose gains (dB) are  a + b*L + c*R : L the breath (0..1), R = log2(f0/fref).
Fitted by least squares on every measured frame's harmonic levels (each frame normalised to its
own total power), the reference's loudness mapped to L in [Llo, 1].

   python fit.py trumpet frames.npz      ->  lib/trumpet_fit.lib
   python fit.py duduk   frames.npz      ->  lib/duduk_fit.lib
frames.npz: f0 (Hz), lvl (dB, the frame's loudness), H (dB, harmonics 1..K) for voiced frames
(made by measure_*.py in this folder)."""
import sys, os, numpy as np
from scipy.optimize import least_squares
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "..", ".."))
SR = 48000
RIDGE = 0.25
CFG = {
    "trumpet": dict(centres=[250, 450, 800, 1500, 2600, 4500, 8000], q=1.0, fref=330, llo=0.35),
    "duduk":   dict(centres=[300, 550, 950, 1600, 2600, 4200, 7000], q=1.0, fref=300, llo=0.3, ridge=1.0),
}

def peak_db(f, fc, q, g):
    """dB response of an RBJ peaking EQ at frequencies f (any shape), gain g dB (broadcast)."""
    A = 10 ** (g / 40); w0 = 2 * np.pi * fc / SR; al = np.sin(w0) / (2 * q)
    b0, b1, b2 = 1 + al * A, -2 * np.cos(w0), 1 - al * A
    a0, a1, a2 = 1 + al / A, -2 * np.cos(w0), 1 - al / A
    z = np.exp(-1j * 2 * np.pi * f / SR)
    return 20 * np.log10(np.abs((b0 + b1 * z + b2 * z * z) / (a0 + a1 * z + a2 * z * z)))

def model(p, f0, L, R, K, cfg):
    nb = len(cfg["centres"]); p = p.reshape(3, nb)
    k = np.arange(1, K + 1)[None, :]; f = k * f0[:, None]
    lv = -20 * np.log10(k) * np.ones_like(f)
    for b, fc in enumerate(cfg["centres"]):
        g = p[0, b] + p[1, b] * L + p[2, b] * R
        lv = lv + peak_db(f, fc, cfg["q"], g[:, None])
    return lv                                     # the level is free per frame (see res)

def breath(lvl, llo):
    lo, hi = np.percentile(lvl, [5, 95])
    return llo + (1 - llo) * np.clip((lvl - lo) / (hi - lo), 0, 1.1)

def fit(inst, path):
    cfg = CFG[inst]; d = np.load(path)
    f0, lvl, H = d["f0"], d["lvl"], d["H"]
    K = H.shape[1]
    rng = np.random.default_rng(0); sel = rng.choice(len(f0), min(1200, len(f0)), replace=False)
    f0, lvl, H = f0[sel], lvl[sel], H[sel]
    tot = 10 * np.log10(np.nansum(10 ** (H / 10), 1)); Hr = H - tot[:, None]
    L = breath(lvl, cfg["llo"]); R = np.log2(f0 / cfg["fref"])
    ok = np.isfinite(Hr) & (Hr > -65) & ((np.arange(1, K + 1)[None, :] * f0[:, None]) < 14000)
    nb = len(cfg["centres"])
    W = ok.astype(float); Hz = np.where(ok, Hr, 0)
    def err(p):                                   # each frame's own level is free: remove its mean error
        e = (model(p, f0, L, R, K, cfg) - Hz) * W
        e = e - (e.sum(1) / W.sum(1))[:, None] * W
        return e[ok]
    def res(p):
        return np.concatenate([np.clip(err(p), -30, 30), cfg.get("ridge", RIDGE) * np.sqrt(ok.sum() / len(p)) * p / 10])   # ridge: keep gains sane
    r = least_squares(res, np.zeros(3 * nb), loss="soft_l1", f_scale=4)
    p = r.x; e = err(p)
    print(f"{inst}: rms error {np.sqrt(np.mean(e**2)):.2f} dB, median |e| {np.median(np.abs(e)):.2f} dB per harmonic")
    return p.reshape(3, nb), cfg

def norm_poly(p, cfg):
    """The bank's loudness (dB, sum of harmonics) changes with breath and register: fit
    n(L, R) = n0 + n1 L + n2 L^2 + n3 R + n4 R^2 + n5 L R, so the instrument can take it out."""
    Ls, Rs = np.meshgrid(np.linspace(0, 1.25, 11), np.linspace(-0.8, 1.0, 10))
    Ls, Rs = Ls.ravel(), Rs.ravel()
    f0 = cfg["fref"] * 2 ** Rs
    lv = model(p.ravel(), f0, Ls, Rs, 60, cfg)
    lv = np.where(np.arange(1, 61)[None, :] * f0[:, None] < 16000, lv, -200)
    tot = 10 * np.log10(np.sum(10 ** (lv / 10), 1))
    X = np.stack([np.ones_like(Ls), Ls, Ls ** 2, Rs, Rs ** 2, Ls * Rs], 1)
    c, *_ = np.linalg.lstsq(X, tot, rcond=None)
    print("bank loudness poly", np.round(c, 2), "max err %.2f dB" % np.max(np.abs(X @ c - tot)))
    return c

def read(inst):
    g = {}
    for l in open(os.path.join(ROOT, "lib", f"{inst}_fit.lib")):
        if "=" in l and not l.startswith("//"):
            k, v = l.split("=", 1); g[k.strip()] = eval(v.strip().rstrip(";"))
    return np.array([g["a"], g["b"], g["c"]])

def write(inst, p, cfg):
    out = os.path.join(ROOT, "lib", f"{inst}_fit.lib")
    fmt = lambda v: "(" + ", ".join("%.3f" % x for x in v) + ")"
    with open(out, "w") as fh:
        fh.write(f"// {inst}: tone fitted to ROLI's Seaboard demo (generated by tools/fitting/seaboard/brass-duduk/fit.py).\n")
        fh.write("// Peaking filters (RBJ, fixed centres and Q); gain dB = a + b*breath + c*log2(f0/fref).\n")
        fh.write(f"centres = {fmt(cfg['centres'])};\nq = {cfg['q']};\nfref = {cfg['fref']};\n")
        fh.write(f"a = {fmt(p[0])};\nb = {fmt(p[1])};\nc = {fmt(p[2])};\n")
        fh.write("// the bank's loudness in dB: n0 + n1 L + n2 L^2 + n3 R + n4 R^2 + n5 L R (taken out by the instrument)\n")
        fh.write(f"norm = {fmt(norm_poly(p, cfg))};\n")
    print("wrote", out)

if __name__ == "__main__":
    inst, path = sys.argv[1], sys.argv[2]
    if path == "--norm":                          # only recompute the loudness table of the lib as it is
        write(inst, read(inst), CFG[inst]); sys.exit()
    p, cfg = fit(inst, path)
    for name, row in zip("abc", p): print(name, np.round(row, 1))
    if "--dry" not in sys.argv: write(inst, p, cfg)
